        x = t[arm]
        m[f'dvT{tag}'] = pct(x['adopt_override_nonsense_target (FT2-B)'])
        m[f'dvAi{tag}'] = pct(x['adopt_override_plaus'])
        m[f'dvAd{tag}'] = pct(x['adopt_decl_plaus'])
