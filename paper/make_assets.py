def load(name):
    return json.loads((RES / name).read_text())


def pct(x, d=1):
    return f'{100 * x:.{d}f}'


def pts(x, d=1):
    s = f'{100 * x:+.{d}f}'
    return s.replace('-', '$-$')


def num(x, d=1):
    return f'{100 * x:.{d}f}'.replace('-', '$-$')


def ci(lo, hi, d=1):
    return f'[{num(lo, d)}, {num(hi, d)}]'


def seeds(values, signed=False):
    vals = list(values.values()) if isinstance(values, dict) else list(values)
    return ', '.join(pts(v) if signed else pct(v) for v in vals)


class Macros:
    def __init__(self):
        self.lines = ['% Generated by paper/make_assets.py from results/*.json. Do not edit by hand.']

    def __setitem__(self, name, value):
        assert name.isalpha(), name
        self.lines.append(f'\\newcommand{{\\{name}}}{{{value}}}')

    def write(self, path):
        path.write_text('\n'.join(self.lines) + '\n')


