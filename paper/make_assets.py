def load(name):
    return json.loads((RES / name).read_text())


def pct(x, d=1):
    return f'{100 * x:.{d}f}'


def pts(x, d=1):
    v = 100 * x
    s = f'{v:+.{d}f}'
    return s.replace('-', '$-$') if s.startswith('-') else s


def ci(lo, hi, d=1):
    f = lambda v: f'{100 * v:.{d}f}'.replace('-', '$-$')
    return f'[{f(lo)}, {f(hi)}]'


class Macros:
    def __init__(self):
        self.lines = ['% Generated by paper/make_assets.py from results/*.json. Do not edit by hand.']

    def __setitem__(self, name, value):
        assert name.isalpha(), name
        self.lines.append(f'\\newcommand{{\\{name}}}{{{value}}}')

    def write(self, path):
        path.write_text('\n'.join(self.lines) + '\n')


