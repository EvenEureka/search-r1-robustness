    m['cfBonusCE'] = pts(v3['Ai'][1] - v3['Ad'][1])
    m['cfAdR'], m['cfAdCE'] = pct(v3['Ad'][0]), pct(v3['Ad'][1])
    m['cfUR'], m['cfUCE'] = pct(v3['U'][0]), pct(v3['U'][1])
